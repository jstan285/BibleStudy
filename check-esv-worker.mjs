import assert from 'node:assert/strict';
import fs from 'node:fs';
const source = fs.readFileSync(new URL('../backend/esv-worker.mjs', import.meta.url),'utf8');
const study = JSON.parse(fs.readFileSync(new URL('../docs/studies/make-way-2026-10-11.json',import.meta.url)));
const catalog = JSON.parse(fs.readFileSync(new URL('../docs/studies/index.json',import.meta.url)));
let upstream = 0, mode = 'ok', ip = 0;
const fresh = () => import('data:text/javascript;base64,'+Buffer.from(source+'\n//'+Math.random()).toString('base64'));
const fetchOriginal = globalThis.fetch;
globalThis.fetch = async (target, options) => {
  const url = new URL(target);
  if (url.hostname === 'jstan285.github.io') return Response.json(url.pathname.endsWith('/index.json') ? catalog : study);
  assert.equal(url.hostname,'api.esv.org');
  assert.equal(options.headers.Authorization,'Token test-only-key');
  assert.equal(url.searchParams.get('include-copyright'),'true');
  assert.equal(url.searchParams.get('include-short-copyright'),'false');
  upstream++;
  if (mode === 'throttle') return new Response('',{status:429});
  const ref = url.searchParams.get('q');
  const m = / (\d+):(\d+)(?:-(\d+))?$/.exec(ref);
  const start=1000000+Number(m[1])*1000+Number(m[2]);
  const end=1000000+Number(m[1])*1000+Number(m[3]||m[2]);
  return Response.json({canonical:ref,parsed:[[start,mode==='wrong-range'?end+1:end]],passages:['<p>Test passage</p><p>ESV copyright notice</p>']});
};
try {
  const {default:worker,validateReferences} = await fresh();
  const request = (path,extra={}) => new Request('https://example.workers.dev'+path,{headers:{Origin:'https://jstan285.github.io','CF-Connecting-IP':String(++ip)},...extra});
  const env={ESV_API_KEY:'test-only-key'};
  assert.equal(validateReferences(study).length,11);
  assert.throws(()=>validateReferences({steps:[{kind:'discussion',refs:['Jude 1:1-20']}]}),/limits/);
  assert.throws(()=>validateReferences({steps:[{kind:'discussion',refs:['Genesis 3:8-1']}]}),/invalid/);
  assert.throws(()=>validateReferences({steps:[{kind:'discussion',refs:['Unknown 1:1']}]}),/unsupported/);
  assert.equal((await worker.fetch(request('/health'),{})).status,200);
  assert.equal((await worker.fetch(request('/study?id=x'),{})).status,503);
  assert.equal((await worker.fetch(request('/study?id=../private'),env)).status,400);
  assert.equal((await worker.fetch(request('/study?id=x',{headers:{Origin:'https://other.example'}}),env)).status,403);
  assert.equal((await worker.fetch(request('/study',{method:'POST'}),env)).status,405);
  assert.equal((await worker.fetch(request('/study',{method:'OPTIONS'}),env)).status,204);
  const absent=await worker.fetch(request('/study?id=missing'),env);
  assert.equal(absent.status,404); assert.equal(upstream,0);
  const path='/study?id='+study.id;
  const responses=await Promise.all([worker.fetch(request(path),env),worker.fetch(request(path),env)]);
  assert.equal(upstream,11,'Concurrent loads should share one batch');
  const data=await responses[0].json();
  assert.equal(Object.keys(data.readings).length,11); assert.equal(data.translation,'ESV');
  assert.equal(responses[0].headers.get('Cache-Control'),'no-store');
  assert.equal(responses[0].headers.get('Access-Control-Allow-Origin'),'https://jstan285.github.io');
  await worker.fetch(request(path),env); assert.equal(upstream,11,'One-minute memory reuse failed');
  const repeated=request(path,{headers:{'CF-Connecting-IP':'same-person'}});
  for(let i=0;i<4;i++) assert.equal((await worker.fetch(repeated,env)).status,200);
  assert.equal((await worker.fetch(repeated,env)).status,429);
  mode='throttle'; const throttled=await fresh();
  const failure=await throttled.default.fetch(request(path),env);
  assert.equal(failure.status,429); assert(!(await failure.text()).includes(env.ESV_API_KEY));
  mode='wrong-range'; const wrong=await fresh();
  assert.equal((await wrong.default.fetch(request(path),env)).status,502);
  console.log('Worker checks passed: 11 ranges, CORS, published studies only, secret isolation, quotation limits, throttling, concurrent loads, memory expiry configuration, upstream range validation.');
} finally {globalThis.fetch=fetchOriginal;}
